import { Trip, Currency, Activity } from '../types';

export const CURRENCY_RATES: Record<Currency, { symbol: string; rate: number; name: string }> = {
  USD: { symbol: '$', rate: 1.0, name: 'US Dollar' },
  EUR: { symbol: '€', rate: 0.92, name: 'Euro' },
  GBP: { symbol: '£', rate: 0.79, name: 'British Pound' },
  JPY: { symbol: '¥', rate: 154.5, name: 'Japanese Yen' },
  CAD: { symbol: 'CA$', rate: 1.36, name: 'Canadian Dollar' },
  AUD: { symbol: 'A$', rate: 1.52, name: 'Australian Dollar' },
  INR: { symbol: '₹', rate: 83.4, name: 'Indian Rupee' },
  CHF: { symbol: 'CHF', rate: 0.90, name: 'Swiss Franc' },
};

export function formatCurrency(amountUSD: number, currency: Currency | string = 'USD'): string {
  const code = (typeof currency === 'string' && currency in CURRENCY_RATES ? currency : 'USD') as Currency;
  const info = CURRENCY_RATES[code] || CURRENCY_RATES.USD;
  const converted = amountUSD * info.rate;
  if (code === 'JPY') {
    return `${info.symbol}${Math.round(converted).toLocaleString()}`;
  }
  return `${info.symbol}${converted.toLocaleString(undefined, { minimumFractionDigits: 0, maximumFractionDigits: 0 })}`;
}

